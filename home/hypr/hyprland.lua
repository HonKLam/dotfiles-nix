-- SUPER+SHIFT+M restored to addmaster (see master-layout binds below).
-- Shutdown command moved to SUPER+ALT+SHIFT+M so it isn't lost.
hl.bind(mainMod .. " + ALT + SHIFT + M", hl.dsp.exec_cmd("command -v hyprshutdown >/dev/null 2>&1 && hyprshutdown || hyprctl dispatch 'hl.dsp.exit()'"))

hl.bind(mainMod .. " + V", hl.dsp.window.float({ action = "toggle" }))
hl.bind(mainMod .. " + F", hl.dsp.window.fullscreen({ mode = "maximized", action = "toggle" }))

-- hl.bind(mainMod .. " + P", hl.dsp.window.pseudo())
